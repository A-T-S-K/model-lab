import { createHash } from 'node:crypto';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Hash the complete production implementation, including evidence presentation and
// build inputs. Tests/docs/benchmarks and this generated output are not runtime.
const directories = ['model', 'trace', 'inspect', 'archive', 'experiments', 'app'];
const inputs = ['fixtures/canonical.initial.json', 'package.json', 'package-lock.json',
  'tsconfig.json', 'index.html', 'scripts/runtime-identity.mjs',
  'research/pythia/adapter.py', 'research/pythia/server.py', 'research/pythia/requirements.lock',
  'research/pythia/dependencies.json', 'research/pythia/model-lock.json', 'research/pythia/profile.json', 'research/pythia/profile-generation.json', 'research/pythia/source.json', 'research/pythia/profile-legacy.json',
  'fixtures/noncanonical.initial.json','research/witnesses/mlp.py','research/witnesses/adapter.py','research/witnesses/fixtures.py','research/witnesses/profile.json'];
export const generatedPath = 'runtime/revision.ts';

export async function runtimeSources(root) {
  const paths = [...inputs];
  async function visit(directory) {
    for (const entry of await readdir(join(root, directory), { withFileTypes: true })) {
      const path = `${directory}/${entry.name}`;
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile()) paths.push(path);
      else throw new Error(`Unsupported runtime source entry: ${path}`);
    }
  }
  for (const directory of directories) await visit(directory);
  // Lexical byte ordering is independent of locale and filesystem enumeration.
  return paths.sort();
}

export async function runtimeIdentity(root) {
  const paths = await runtimeSources(root);
  const hash = createHash('sha256');
  hash.update('model-lab-runtime-v1\0');
  for (const path of paths) {
    const bytes = await readFile(join(root, path));
    hash.update(`${Buffer.byteLength(path)}:${path}:${bytes.length}:`);
    hash.update(bytes);
  }
  return { revision: `sha256:${hash.digest('hex')}`, sources: paths };
}

export async function generateRuntimeIdentity(root) {
  const identity = await runtimeIdentity(root);
  const output = join(root, generatedPath);
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, `// Generated by scripts/runtime-identity.mjs. Do not edit.\n` +
    `export const RUNTIME_REVISION = ${JSON.stringify(identity.revision)};\n`);
  return identity;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const identity = await generateRuntimeIdentity(root);
  console.log(`Model Lab runtime ${identity.revision} (${identity.sources.length} source files)`);
}
